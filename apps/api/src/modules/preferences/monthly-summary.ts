import { formatINR, formatMonthKey } from '@moneylens/shared';
import type { MonthlyReport } from '@moneylens/types';
import type { MailMessage } from '../../lib/mailer';

const TOP_CATEGORIES = 5;
const BIGGEST_PAYMENTS = 3;
const WORTH_A_LOOK = 3;

/** "8% less than August 2026" / "about the same as August 2026". */
function versus(now: number, before: number, label: string): string | null {
  if (before <= 0) return null;
  const pct = Math.round(((now - before) / before) * 100);
  if (pct === 0) return `about the same as ${label}`;
  return `${Math.abs(pct)}% ${pct > 0 ? 'more' : 'less'} than ${label}`;
}

/** A label and an amount, padded so the amounts line up in plain text. */
const line = (label: string, amount: string, note?: string | null) =>
  `${label.padEnd(10)}${amount}${note ? `  (${note})` : ''}`;

/** "12 Sep" for a transaction date in IST. */
function shortDay(iso: string): string {
  return new Intl.DateTimeFormat('en-IN', {
    day: 'numeric',
    month: 'short',
    timeZone: 'Asia/Kolkata',
  }).format(new Date(iso));
}

/**
 * The monthly summary email, in plain text so it reads the same in every
 * mail app. Every figure comes from the monthly report (the analytics
 * engine); nothing is generated by a language model.
 */
export function monthlySummaryEmail(
  report: MonthlyReport,
  opts: { to: string; name: string; appUrl: string },
): MailMessage {
  const month = formatMonthKey(report.month);
  const t = report.totals;
  const before = report.compareTotals;
  const compareLabel = report.compareMonth ? formatMonthKey(report.compareMonth) : '';
  const firstName = opts.name.trim().split(/\s+/)[0] || 'there';

  const out: string[] = [`Hi ${firstName},`, '', `Here is how ${month} went.`, ''];
  out.push(
    line(
      'Spent',
      formatINR(t.spendingPaise),
      before && versus(t.spendingPaise, before.spendingPaise, compareLabel),
    ),
    line('Received', formatINR(t.incomePaise)),
  );
  if (t.incomePaise > 0) {
    out.push(
      line(
        t.savedPaise >= 0 ? 'Saved' : 'Overspent',
        formatINR(Math.abs(t.savedPaise)),
        t.savedPaise >= 0 && t.savingsRatePct !== null
          ? `${Math.round(t.savingsRatePct)}% of what came in`
          : null,
      ),
    );
  }

  const categories = report.categories
    .filter((c) => c.currentPaise > 0)
    .sort((a, b) => b.currentPaise - a.currentPaise)
    .slice(0, TOP_CATEGORIES);
  if (categories.length > 0) {
    out.push('', 'Where the money went');
    for (const c of categories) {
      const change =
        c.changeVsPreviousPct === null || c.previousPaise === 0
          ? ''
          : c.changeVsPreviousPct === 0
            ? ', same as before'
            : `, ${c.changeVsPreviousPct > 0 ? 'up' : 'down'} ${Math.abs(Math.round(c.changeVsPreviousPct))}%`;
      out.push(`- ${c.name}: ${formatINR(c.currentPaise)}${change}`);
    }
  }

  const biggest = report.biggestTransactions
    .filter((tx) => tx.flow === 'OUT')
    .slice(0, BIGGEST_PAYMENTS);
  if (biggest.length > 0) {
    out.push('', 'Biggest payments');
    for (const tx of biggest) {
      out.push(
        `- ${shortDay(tx.date)}, ${tx.merchantName ?? 'Unknown'}: ${formatINR(tx.amountPaise)}`,
      );
    }
  }

  const notes = [...report.savingOpportunities, ...report.changes]
    .slice(0, WORTH_A_LOOK)
    .map((i) => i.title);
  if (notes.length > 0) {
    out.push('', 'Worth a look');
    for (const note of notes) out.push(`- ${note}`);
  }

  if (report.health.score !== null) {
    out.push('', `Money health score: ${Math.round(report.health.score)} out of 100`);
  }

  const base = opts.appUrl.replace(/\/+$/, '');
  out.push(
    '',
    `See the full report: ${base}/reports?month=${report.month}`,
    '',
    'You get this email because the monthly summary is switched on in MoneyLens Settings.',
    'Switch it off there at any time.',
    '',
    'MoneyLens',
  );

  return {
    to: opts.to,
    subject: `Your MoneyLens summary for ${month}`,
    text: out.join('\n'),
  };
}
